#!/usr/bin/env sh
# Installs or updates the platform on one Linux server with Docker.
#
#   ./setup.sh <edge host> <dashboard host> <acme email> [public IPv4]
#   ./setup.sh edge.ibos.io tracking.ibos.io admin@ibos.io 203.0.113.10
#
# The first run writes .env with generated secrets and prints the dashboard password. Later runs keep the secrets,
# update the host names, rebuild and restart.
set -eu
cd "$(dirname "$0")"

if [ $# -lt 3 ]; then
  sed -n '2,8p' "$0" | sed 's/^# \{0,1\}//'
  exit 1
fi
EDGE_HOSTNAME=$1
DASHBOARD_HOST=$2
ACME_EMAIL=$3
EDGE_IPV4=${4:-}

command -v docker >/dev/null 2>&1 || { echo "Docker is not installed: https://docs.docker.com/engine/install/" >&2; exit 1; }
docker compose version >/dev/null 2>&1 || { echo "The Docker Compose plugin is missing." >&2; exit 1; }
command -v openssl >/dev/null 2>&1 || { echo "openssl is needed to generate secrets." >&2; exit 1; }

if [ -z "$EDGE_IPV4" ]; then
  # Asks an outside service for this server's public address; pass it as the 4th argument to skip this.
  EDGE_IPV4=$(curl -4 -fsS --max-time 10 https://ifconfig.me 2>/dev/null || true)
  [ -n "$EDGE_IPV4" ] && echo "Public IPv4 detected: $EDGE_IPV4"
fi

set_var() {
  if grep -q "^$1=" .env; then
    sed -i "s|^$1=.*|$1=$2|" .env
  else
    printf '%s=%s\n' "$1" "$2" >> .env
  fi
}

if [ ! -f .env ]; then
  umask 077
  cat > .env <<EOF
# Generated by setup.sh. Keep this file private and backed up: it holds the platform's secrets.
ADMIN_API_KEY=$(openssl rand -hex 24)
INTERNAL_API_TOKEN=$(openssl rand -hex 24)
SESSION_SECRET=$(openssl rand -hex 32)
EOF
else
  echo ".env exists: keeping its secrets."
fi
# Installs from before PostgreSQL have an .env without it.
grep -q '^POSTGRES_PASSWORD=' .env || set_var POSTGRES_PASSWORD "$(openssl rand -hex 24)"
set_var EDGE_HOSTNAME "$EDGE_HOSTNAME"
set_var DASHBOARD_HOST "$DASHBOARD_HOST"
set_var ACME_EMAIL "$ACME_EMAIL"
set_var EDGE_IPV4 "$EDGE_IPV4"
mkdir -p geoip

# Caddy can only get certificates for names that already point here.
for host in "$EDGE_HOSTNAME" "$DASHBOARD_HOST"; do
  resolved=$(getent ahostsv4 "$host" 2>/dev/null | awk 'NR==1 {print $1}')
  if [ -z "$EDGE_IPV4" ] || [ "$resolved" != "$EDGE_IPV4" ]; then
    echo "WARNING: $host resolves to '${resolved:-nothing}', expected '${EDGE_IPV4:-this server}'." >&2
    echo "         Create an A record for it; Caddy retries the certificate once DNS is right." >&2
  fi
done

docker compose up -d --build
docker compose ps

echo
echo "Dashboard:  https://$DASHBOARD_HOST"
echo "Create the first account there (Sign up). For Google sign-in and super-admins, set GOOGLE_CLIENT_ID,"
echo "GOOGLE_CLIENT_SECRET and SUPER_ADMIN_EMAILS in deploy/server/.env and run this script again."
echo "Customers point their tracking subdomain at $EDGE_HOSTNAME with a CNAME record."
